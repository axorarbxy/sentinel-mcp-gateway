"""Train a trace-grouped synthetic benchmark classifier for event-stream signals.

This offline research model is kept separate from the gateway's enforcement path.
It must not be treated as production-calibrated until validated on real traces.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import joblib
import pandas as pd
from sklearn.compose import ColumnTransformer
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import classification_report, confusion_matrix, f1_score
from sklearn.model_selection import GroupShuffleSplit
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import OneHotEncoder

from event_stream_dataset import CATEGORICAL_FEATURES, MODEL_FEATURES, NUMERIC_FEATURES

MACHINE_LEARNING_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_INPUT = MACHINE_LEARNING_ROOT / "data" / "event_stream" / "synthetic_event_stream.csv"
DEFAULT_OUTPUT = MACHINE_LEARNING_ROOT / "ml" / "artifacts" / "event_stream_synthetic_model.joblib"


def train(input_path: Path, model_path: Path, seed: int = 42) -> dict:
    frame = pd.read_csv(input_path)
    missing = sorted(set([*MODEL_FEATURES, "attack_class", "trace_id"]) - set(frame.columns))
    if missing:
        raise ValueError(f"Dataset is missing required columns: {', '.join(missing)}")
    if frame["attack_class"].nunique() < 2:
        raise ValueError("Training data must contain at least two attack_class labels")

    X = frame[MODEL_FEATURES].copy()
    y = frame["attack_class"].astype(str)
    groups = frame["trace_id"].astype(str)
    split = GroupShuffleSplit(n_splits=1, test_size=0.25, random_state=seed)
    train_indices, test_indices = next(split.split(X, y, groups=groups))

    preprocessor = ColumnTransformer(
        transformers=[
            ("numeric", "passthrough", NUMERIC_FEATURES),
            ("categorical", OneHotEncoder(handle_unknown="ignore"), CATEGORICAL_FEATURES),
        ],
        remainder="drop",
    )
    model = Pipeline([
        ("features", preprocessor),
        ("classifier", RandomForestClassifier(
            n_estimators=220,
            min_samples_leaf=2,
            class_weight="balanced_subsample",
            random_state=seed,
            n_jobs=-1,
        )),
    ])
    model.fit(X.iloc[train_indices], y.iloc[train_indices])
    predictions = model.predict(X.iloc[test_indices])
    labels = sorted(y.unique())
    report = classification_report(
        y.iloc[test_indices], predictions, labels=labels, output_dict=True, zero_division=0,
    )

    feature_names = model.named_steps["features"].get_feature_names_out()
    importances = model.named_steps["classifier"].feature_importances_
    top_signals = [
        {"feature": str(feature_names[index]), "importance": round(float(importances[index]), 6)}
        for index in importances.argsort()[::-1][:20]
    ]
    metrics = {
        "model_type": "RandomForestClassifier",
        "training_scope": "synthetic_event_stream_benchmark_only",
        "input_path": str(input_path),
        "model_path": str(model_path),
        "seed": seed,
        "total_events": int(len(frame)),
        "train_events": int(len(train_indices)),
        "test_events": int(len(test_indices)),
        "train_traces": int(groups.iloc[train_indices].nunique()),
        "test_traces": int(groups.iloc[test_indices].nunique()),
        "classes": labels,
        "macro_f1": round(float(f1_score(y.iloc[test_indices], predictions, average="macro")), 6),
        "classification_report": report,
        "confusion_matrix": confusion_matrix(y.iloc[test_indices], predictions, labels=labels).tolist(),
        "top_signals": top_signals,
        "limitations": [
            "Synthetic distributions are authored scenarios and do not measure real attack prevalence.",
            "Trace groups are held out, but validation on real broker telemetry is still required.",
            "This artifact is not loaded by the gateway and does not make enforcement decisions.",
        ],
    }
    model_path.parent.mkdir(parents=True, exist_ok=True)
    joblib.dump({"pipeline": model, "features": MODEL_FEATURES, "classes": labels}, model_path)
    model_path.with_suffix(".metrics.json").write_text(json.dumps(metrics, indent=2), encoding="utf-8")
    return metrics


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT, help="CSV generated by event_stream_dataset.py")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT, help="output model artifact path")
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()
    result = train(args.input, args.output, args.seed)
    print(json.dumps({
        "macro_f1": result["macro_f1"],
        "train_events": result["train_events"],
        "test_events": result["test_events"],
        "train_traces": result["train_traces"],
        "test_traces": result["test_traces"],
        "classes": result["classes"],
        "model": result["model_path"],
        "metrics": str(args.output.with_suffix(".metrics.json")),
    }, indent=2))


if __name__ == "__main__":
    main()
